#!/usr/bin/env node
// Bricolage Grotesque at the prototype's optical sizes. The prototype loads the variable font
// (opsz 12..96), so the browser draws every display size with opsz = its font size: a 30px title
// is narrower and tighter than the static font's default instance. Android can't set font
// variations, so we ship one static instance per (weight, size) the prototype uses, fetched from
// Google Fonts, and fontFamily('display', weight, size) picks the matching one.
//   node tools/gen-display-fonts.mjs
// Writes packages/ui/src/fonts/display/*.ttf and packages/ui/src/fonts/display.ts.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const weights = [600, 800];
// Every font-size the prototype sets on var(--f-d), plus the kit's type scale.
const css = readdirSync(join(root, 'prototype/src'))
  .filter((f) => f.endsWith('.html'))
  .map((f) => readFileSync(join(root, 'prototype/src', f), 'utf8'))
  .join('\n');
const sizes = new Set([16, 18, 22, 28, 30, 34, 36]);
for (const rule of css.match(/[^{}]*\{[^}]*var\(--f-d\)[^}]*\}/g) ?? [])
  for (const m of rule.matchAll(/font-size:\s*([\d.]+)px/g)) sizes.add(Math.round(Number(m[1])));
const opsz = [...sizes].map((n) => Math.min(96, Math.max(12, n))).sort((a, b) => a - b);

const out = join(root, 'packages/ui/src/fonts/display');
mkdirSync(out, { recursive: true });
const entries = [];
for (const w of weights)
  for (const o of [...new Set(opsz)]) {
    // An old user agent gets TrueType (Android needs ttf, not woff2).
    const face = await fetch(
      `https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@${o},${w}`,
      { headers: { 'User-Agent': 'Mozilla/4.0' } },
    ).then((r) => r.text());
    const url = face.match(/url\((https:[^)]+\.ttf)\)/)?.[1];
    if (!url) throw new Error(`no ttf for opsz ${o} wght ${w}`);
    const buf = Buffer.from(await fetch(url).then((r) => r.arrayBuffer()));
    const file = `bricolage-${w}-${o}.ttf`;
    writeFileSync(join(out, file), buf);
    entries.push({ name: `Bricolage_${w}_${o}`, file, w, o });
    console.log(`wrote ${file} (${buf.length} bytes)`);
  }

writeFileSync(
  join(root, 'packages/ui/src/fonts/display.ts'),
  `// Generated by tools/gen-display-fonts.mjs. Do not edit.
/* eslint-disable @typescript-eslint/no-require-imports */
/** Optical sizes shipped for Bricolage Grotesque, per weight. */
export const displayOpsz = ${JSON.stringify([...new Set(opsz)])} as const;

/** Load with useFonts({ ...displayFonts }) in the app's root layout. */
export const displayFonts = {
${entries.map((e) => `  ${e.name}: require('./display/${e.file}') as number,`).join('\n')}
};
`,
);
console.log(`wrote packages/ui/src/fonts/display.ts (${entries.length} faces)`);
