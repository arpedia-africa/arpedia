#!/usr/bin/env node
// Generate icon path tables from the prototypes' Myna UI sprites, so the app and the admin draw exactly
// the icons the prototypes show. Re-run after a sprite changes:
//   node tools/gen-icons.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const attr = (tag, name) => (tag.match(new RegExp(`\\s${name}="([^"]*)"`)) || [])[1];

// app sprite → packages/ui (React Native), admin sprite → apps/admin (web)
for (const [from, to] of [
  ['prototype/src/01-shell.html', 'packages/ui/src/icons/paths.ts'],
  ['admin/src/01-sprite.html', 'apps/admin/components/icon-paths.ts'],
]) {
  const src = readFileSync(join(root, from), 'utf8');
  const icons = {};
  for (const m of src.matchAll(/<symbol id="i-([a-z0-9-]+)"([^>]*)>([\s\S]*?)<\/symbol>/g)) {
    const [, id, attrs, inner] = m;
    if (/<image|<use/.test(inner)) continue; // brand marks (app icon, sun) are images, not strokes
    const viewBox = attr(attrs, 'viewBox') ?? '0 0 24 24';
    const shapes = [];
    for (const el of inner.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?>/g)) {
      const [, tag, a] = el;
      const props = {};
      for (const p of a.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) {
        const key = p[1].replace(/-([a-z])/g, (_, c) => c.toUpperCase());
        props[key] = p[2];
      }
      shapes.push({ tag, ...props });
    }
    const fill = /\bfill="currentColor"/.test(attrs) || /class="[^"]*fill/.test(attrs);
    icons[id] = { viewBox, fill: fill || undefined, shapes };
  }

  const out = join(root, to);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(
    out,
    `// Generated by tools/gen-icons.mjs from ${from} (Myna UI icons). Do not edit.\n` +
      `export interface IconShape { tag: 'path' | 'circle' | 'rect' | 'line' | 'polyline' | 'polygon' | 'ellipse'; [prop: string]: string }\n` +
      `export interface IconDef { viewBox: string; fill?: boolean; shapes: IconShape[] }\n\n` +
      `export const icons = ${JSON.stringify(icons, null, 1)} as const satisfies Record<string, IconDef>;\n\n` +
      `export type IconName = keyof typeof icons;\n`,
  );
  console.log(`Wrote ${Object.keys(icons).length} icons to ${to}`);
}
