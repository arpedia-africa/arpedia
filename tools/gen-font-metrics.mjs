#!/usr/bin/env node
// Writes packages/ui/src/fonts/metrics.ts: hhea ascent/descent (per em) for every font family name the
// app loads. Text.tsx uses them to place glyphs inside a line box where Chrome places them.
//   node tools/gen-font-metrics.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** [ascent, descent] per em from the hhea table (what Skia/FreeType report on Android and in Chrome). */
function metrics(file) {
  const buf = readFileSync(file);
  const tables = {};
  for (let i = 0, n = buf.readUInt16BE(4); i < n; i++) {
    const o = 12 + i * 16;
    tables[buf.toString('latin1', o, o + 4)] = buf.readUInt32BE(o + 8);
  }
  const upem = buf.readUInt16BE(tables.head + 18);
  const round = (v) => Math.round(v * 1e6) / 1e6;
  return [round(buf.readInt16BE(tables.hhea + 4) / upem), round(-buf.readInt16BE(tables.hhea + 6) / upem)];
}

const out = {};
for (const pkg of ['inter', 'literata'])
  for (const dir of readdirSync(join(root, 'node_modules/@expo-google-fonts', pkg), { withFileTypes: true }))
    if (dir.isDirectory())
      for (const f of readdirSync(join(root, 'node_modules/@expo-google-fonts', pkg, dir.name)))
        if (f.endsWith('.ttf'))
          out[f.slice(0, -4)] = metrics(join(root, 'node_modules/@expo-google-fonts', pkg, dir.name, f));
const display = join(root, 'packages/ui/src/fonts/display');
for (const f of readdirSync(display).filter((f) => f.endsWith('.ttf'))) {
  const [, w, o] = f.match(/bricolage-(\d+)-(\d+)\.ttf/);
  out[`Bricolage_${w}_${o}`] = metrics(join(display, f));
}

const lines = Object.keys(out)
  .sort()
  .map((k) => `  ${k}: [${out[k].join(', ')}],`);
writeFileSync(
  join(root, 'packages/ui/src/fonts/metrics.ts'),
  `// Generated by tools/gen-font-metrics.mjs. Do not edit.
/** hhea [ascent, descent] per em, by loaded font family name. */
export const fontMetrics: Record<string, readonly [number, number]> = {
${lines.join('\n')}
};
`,
);
console.log(`${lines.length} fonts`);
