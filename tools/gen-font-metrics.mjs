#!/usr/bin/env node
// Writes packages/ui/src/fonts/metrics.ts: hhea ascent/descent and a typical advance (per em) for every
// font family name the app loads. Text.tsx uses them to draw text where and as wide as Chrome does.
//   node tools/gen-font-metrics.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Characters whose mean advance stands for "a typical glyph" (UI text is mostly lowercase).
const TYPICAL = 'abcdefghijklmnopqrstuvwxyzabcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 ';

/** Glyph id for a BMP character from the cmap format 4 subtable (Windows Unicode BMP). */
function glyphId(buf, cmap, ch) {
  for (let i = 0, n = buf.readUInt16BE(cmap + 2); i < n; i++) {
    const rec = cmap + 4 + i * 8;
    const sub = cmap + buf.readUInt32BE(rec + 4);
    if (buf.readUInt16BE(rec) !== 3 || buf.readUInt16BE(rec + 2) !== 1 || buf.readUInt16BE(sub) !== 4)
      continue;
    const segs = buf.readUInt16BE(sub + 6) / 2;
    const ends = sub + 14;
    const starts = ends + segs * 2 + 2;
    const deltas = starts + segs * 2;
    const offsets = deltas + segs * 2;
    for (let s = 0; s < segs; s++) {
      if (ch > buf.readUInt16BE(ends + s * 2)) continue;
      if (ch < buf.readUInt16BE(starts + s * 2)) return 0;
      const ro = buf.readUInt16BE(offsets + s * 2);
      const delta = buf.readInt16BE(deltas + s * 2);
      if (!ro) return (ch + delta) & 0xffff;
      const g = buf.readUInt16BE(offsets + s * 2 + ro + (ch - buf.readUInt16BE(starts + s * 2)) * 2);
      return g ? (g + delta) & 0xffff : 0;
    }
  }
  return 0;
}

/**
 * [ascent, descent, typical advance] per em: hhea ascent/descent (what Skia/FreeType report on Android
 * and in Chrome) and the mean advance of TYPICAL (Text.tsx turns a font-size rounding error into
 * letter spacing with it).
 */
function metrics(file) {
  const buf = readFileSync(file);
  const tables = {};
  for (let i = 0, n = buf.readUInt16BE(4); i < n; i++) {
    const o = 12 + i * 16;
    tables[buf.toString('latin1', o, o + 4)] = buf.readUInt32BE(o + 8);
  }
  const upem = buf.readUInt16BE(tables.head + 18);
  const longMetrics = buf.readUInt16BE(tables.hhea + 34);
  const advance = (g) => buf.readUInt16BE(tables.hmtx + 4 * Math.min(g, longMetrics - 1));
  let sum = 0;
  for (const ch of TYPICAL) sum += advance(glyphId(buf, tables.cmap, ch.charCodeAt(0)));
  const round = (v) => Math.round(v * 1e6) / 1e6;
  return [
    round(buf.readInt16BE(tables.hhea + 4) / upem),
    round(-buf.readInt16BE(tables.hhea + 6) / upem),
    round(sum / TYPICAL.length / upem),
  ];
}

const out = {};
for (const pkg of ['inter', 'literata'])
  for (const dir of readdirSync(join(root, 'node_modules/@expo-google-fonts', pkg), { withFileTypes: true }))
    if (dir.isDirectory())
      for (const f of readdirSync(join(root, 'node_modules/@expo-google-fonts', pkg, dir.name)))
        if (f.endsWith('.ttf'))
          out[f.slice(0, -4)] = metrics(join(root, 'node_modules/@expo-google-fonts', pkg, dir.name, f));
const display = join(root, 'packages/ui/src/fonts/display');
for (const f of readdirSync(display).filter((f) => f.endsWith('.ttf'))) {
  const [, w, o] = f.match(/bricolage-(\d+)-(\d+)\.ttf/);
  out[`Bricolage_${w}_${o}`] = metrics(join(display, f));
}

const lines = Object.keys(out)
  .sort()
  .map((k) => `  ${k}: [${out[k].join(', ')}],`);
writeFileSync(
  join(root, 'packages/ui/src/fonts/metrics.ts'),
  `// Generated by tools/gen-font-metrics.mjs. Do not edit.
/** [hhea ascent, hhea descent, typical advance] per em, by loaded font family name. */
export const fontMetrics: Record<string, readonly [number, number, number]> = {
${lines.join('\n')}
};
`,
);
console.log(`${lines.length} fonts`);
