// Android text drawn like Chrome draws it (the prototype): subpixel glyph positions and unhinted
// advances. React Native creates its text paints with ANTI_ALIAS_FLAG only, so every glyph snaps to a
// whole pixel and long lines drift up to 3px from the prototype. There is no JS switch, so a build-time
// bytecode pass (AGP instrumentation, no React Native fork) ORs Paint.SUBPIXEL_TEXT_FLAG into:
// - every `new TextPaint(flags)` in com.facebook.react.views.text* (measuring and prepared layouts)
// - the paint flags of ReactTextView and ReactEditText, set at the end of their constructors
const fs = require('node:fs');
const path = require('node:path');
const { withAppBuildGradle, withDangerousMod, withGradleProperties } = require('expo/config-plugins');

const MARK = '// arpedia: subpixel text';

// buildSrc loads before the root build script, so it must bring AGP itself (the same version React
// Native's Gradle plugin uses) for the factory to see AGP's classes at configuration time.
const AGP = agpVersion();
const BUILD_SRC_GRADLE = `plugins { id 'java-library' }
repositories { google(); mavenCentral() }
dependencies {
  implementation 'com.android.tools.build:gradle:${AGP}'
  compileOnly 'org.ow2.asm:asm:9.8'
}
`;

function agpVersion() {
  const toml = fs.readFileSync(
    path.join(path.dirname(require.resolve('@react-native/gradle-plugin/package.json')), 'gradle/libs.versions.toml'),
    'utf8',
  );
  return toml.match(/^agp\s*=\s*"([^"]+)"/m)[1];
}

const FACTORY = `import com.android.build.api.instrumentation.AsmClassVisitorFactory;
import com.android.build.api.instrumentation.ClassContext;
import com.android.build.api.instrumentation.ClassData;
import com.android.build.api.instrumentation.InstrumentationParameters;
import org.objectweb.asm.ClassVisitor;
import org.objectweb.asm.MethodVisitor;
import org.objectweb.asm.Opcodes;

/** Generated by apps/mobile/plugins/subpixel-text.js. Do not edit. */
public abstract class SubpixelTextFactory implements AsmClassVisitorFactory<InstrumentationParameters.None> {
  private static final int SUBPIXEL_TEXT_FLAG = 0x80;

  @Override
  public ClassVisitor createClassVisitor(ClassContext context, ClassVisitor next) {
    final int api = getInstrumentationContext().getApiVersion().get();
    final String name = context.getCurrentClassData().getClassName();
    final boolean textView =
        name.equals("com.facebook.react.views.text.ReactTextView")
            || name.equals("com.facebook.react.views.textinput.ReactEditText");
    return new ClassVisitor(api, next) {
      @Override
      public MethodVisitor visitMethod(int access, String method, String desc, String sig, String[] ex) {
        final boolean ctor = textView && method.equals("<init>");
        return new MethodVisitor(api, super.visitMethod(access, method, desc, sig, ex)) {
          @Override
          public void visitMethodInsn(int op, String owner, String m, String d, boolean itf) {
            if (op == Opcodes.INVOKESPECIAL && owner.equals("android/text/TextPaint")
                && m.equals("<init>") && d.equals("(I)V")) {
              super.visitIntInsn(Opcodes.SIPUSH, SUBPIXEL_TEXT_FLAG);
              super.visitInsn(Opcodes.IOR);
            }
            super.visitMethodInsn(op, owner, m, d, itf);
          }

          @Override
          public void visitInsn(int op) {
            if (ctor && op == Opcodes.RETURN) {
              super.visitVarInsn(Opcodes.ALOAD, 0);
              super.visitVarInsn(Opcodes.ALOAD, 0);
              super.visitMethodInsn(Opcodes.INVOKEVIRTUAL, "android/widget/TextView", "getPaintFlags", "()I", false);
              super.visitIntInsn(Opcodes.SIPUSH, SUBPIXEL_TEXT_FLAG);
              super.visitInsn(Opcodes.IOR);
              super.visitMethodInsn(Opcodes.INVOKEVIRTUAL, "android/widget/TextView", "setPaintFlags", "(I)V", false);
            }
            super.visitInsn(op);
          }

          @Override
          public void visitMaxs(int maxStack, int maxLocals) {
            super.visitMaxs(maxStack + 3, maxLocals);
          }
        };
      }
    };
  }

  @Override
  public boolean isInstrumentable(ClassData data) {
    return data.getClassName().startsWith("com.facebook.react.views.text");
  }
}
`;

const APP_GRADLE = `
${MARK}
androidComponents {
    onVariants(selector().all(), { variant ->
        variant.instrumentation.transformClassesWith(SubpixelTextFactory, com.android.build.api.instrumentation.InstrumentationScope.ALL) {}
        variant.instrumentation.setAsmFramesComputationMode(com.android.build.api.instrumentation.FramesComputationMode.COPY_FRAMES)
    })
}
`;

module.exports = function withSubpixelText(config) {
  // AGP loaded from buildSrc needs more class metadata room than Expo's default 512m.
  config = withGradleProperties(config, (cfg) => {
    for (const p of cfg.modResults)
      if (p.type === 'property' && p.key === 'org.gradle.jvmargs')
        p.value = p.value.replace(/-XX:MaxMetaspaceSize=\S+/, '-XX:MaxMetaspaceSize=1024m');
    return cfg;
  });
  config = withAppBuildGradle(config, (cfg) => {
    if (!cfg.modResults.contents.includes(MARK)) cfg.modResults.contents += APP_GRADLE;
    return cfg;
  });
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'buildSrc');
      fs.mkdirSync(path.join(dir, 'src/main/java'), { recursive: true });
      fs.writeFileSync(path.join(dir, 'build.gradle'), BUILD_SRC_GRADLE);
      fs.writeFileSync(path.join(dir, 'src/main/java/SubpixelTextFactory.java'), FACTORY);
      return cfg;
    },
  ]);
};
