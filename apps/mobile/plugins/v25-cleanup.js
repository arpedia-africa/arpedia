// Flow 17 rule 2 · the release replaces v25 (same package, com.arpedia.reader). On the very first
// launch after install or update, remove everything v25 left on the phone (session, downloads,
// caches, databases, preferences and its Android Keystore keys), so the app lands on the normal
// first-run screens. It runs in Application.attachBaseContext: before any content provider, Expo
// module or React Native touches storage, so nothing of the new app exists yet to lose.
// A marker in no_backup/ makes it run once. It also writes files/arpedia-launch.json with
// { "after_v25": true|false } (an update over an older install, or a fresh one), which the JS side
// reports once as the `first_open_after_v25` event (features/17/first-open.ts) and then deletes.
const fs = require('node:fs');
const path = require('node:path');
const { withDangerousMod, withMainApplication } = require('expo/config-plugins');

const kotlin = (pkg) => `package ${pkg}

import android.content.Context
import android.util.Log
import java.io.File
import java.security.KeyStore

/** Generated by plugins/v25-cleanup.js (flow 17): first launch removes v25's local data. */
object V25Cleanup {
  private const val TAG = "V25Cleanup"
  private const val MARKER = "arpedia-first-launch-v1"
  // The process needs these: native libraries and the runtime's code cache.
  private val KEEP = setOf("lib", "code_cache")

  fun run(context: Context) {
    try {
      val marker = File(context.noBackupFilesDir, MARKER)
      if (marker.exists()) return
      val info = context.packageManager.getPackageInfo(context.packageName, 0)
      val afterUpdate = info.firstInstallTime != info.lastUpdateTime
      var removed = 0
      context.dataDir.listFiles()?.forEach { f ->
        if (f.name !in KEEP && f.deleteRecursively()) removed++
      }
      try {
        val ks = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        ks.aliases().toList().forEach { ks.deleteEntry(it) }
      } catch (t: Throwable) {
        Log.w(TAG, "keystore", t)
      }
      context.noBackupFilesDir.mkdirs()
      marker.writeText("1")
      context.filesDir.mkdirs()
      File(context.filesDir, "arpedia-launch.json").writeText("{\\"after_v25\\":$afterUpdate}")
      Log.i(TAG, "first launch: removed $removed entries, afterUpdate=$afterUpdate")
    } catch (t: Throwable) {
      // Never block the app from starting.
      Log.w(TAG, "cleanup failed", t)
    }
  }
}
`;

const HOOK = `
  override fun attachBaseContext(base: android.content.Context) {
    V25Cleanup.run(base)
    super.attachBaseContext(base)
  }
`;

module.exports = function withV25Cleanup(config) {
  const pkg = config.android?.package;
  if (!pkg) throw new Error('v25-cleanup: android.package is not set');
  config = withMainApplication(config, (cfg) => {
    const src = cfg.modResults.contents;
    if (!src.includes('V25Cleanup.run(base)')) {
      const cls = /(class MainApplication\s*:[^{]*\{\n)/;
      if (!cls.test(src)) throw new Error('v25-cleanup: MainApplication class not found');
      cfg.modResults.contents = src.replace(cls, `$1${HOOK}`);
    }
    return cfg;
  });
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/java', ...pkg.split('.'));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'V25Cleanup.kt'), kotlin(pkg));
      return cfg;
    },
  ]);
};
