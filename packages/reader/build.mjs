// Builds the reader bundle (flow 04 rule 1): foliate-js + the bridge in one local HTML page, as a
// TypeScript string module the app loads into its WebView. Fonts ride along as data: URLs, so the
// page needs no network. Runs on install (postinstall) and with `pnpm --filter @arpedia/reader build`.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

// foliate formats we never open (our books are EPUB built by flow 12). Left as dead dynamic imports.
const unused = ['./vendor/zip.js', './vendor/fflate.js', './comic-book.js', './fb2.js', './mobi.js', './tts.js'];

const js = await build({
  entryPoints: [join(here, 'src/web/main.ts')],
  bundle: true,
  format: 'iife',
  target: 'chrome100',
  minify: true,
  write: false,
  legalComments: 'none',
  define: { __BUNDLE_VERSION__: '"0"' },
  plugins: [
    {
      name: 'skip-unused-foliate-formats',
      setup(b) {
        b.onResolve({ filter: /^\.\/(vendor\/(zip|fflate)|comic-book|fb2|mobi|tts)\.js$/ }, (a) =>
          unused.includes(a.path) ? { path: a.path, external: true } : undefined,
        );
      },
    },
  ],
});
let code = js.outputFiles[0].text;
const version = createHash('sha256').update(code).digest('hex').slice(0, 12);
code = code.replace('"0"', JSON.stringify(version));

const font = (pkg, file) => {
  const path = require.resolve(`@expo-google-fonts/${pkg}/${file}`);
  return `url(data:font/ttf;base64,${readFileSync(path).toString('base64')}) format('truetype')`;
};
const faces = [
  ['Literata', 400, 'normal', font('literata', '400Regular/Literata_400Regular.ttf')],
  ['Literata', 400, 'italic', font('literata', '400Regular_Italic/Literata_400Regular_Italic.ttf')],
  ['Literata', 700, 'normal', font('literata', '700Bold/Literata_700Bold.ttf')],
  ['Inter', 400, 'normal', font('inter', '400Regular/Inter_400Regular.ttf')],
  ['Inter', 700, 'normal', font('inter', '700Bold/Inter_700Bold.ttf')],
  ['Bricolage Grotesque', 800, 'normal', font('bricolage-grotesque', '800ExtraBold/BricolageGrotesque_800ExtraBold.ttf')],
]
  .map(([f, w, s, src]) => `@font-face{font-family:'${f}';font-weight:${w};font-style:${s};src:${src};font-display:block}`)
  .join('');

// Section documents are blob: iframes; fonts are declared there too by the bridge (it injects this
// sheet into each section), so it is exported separately as well.
const html =
  '<!doctype html><html><head><meta charset="utf-8">' +
  '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">' +
  `<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline' blob:; img-src blob: data:; font-src data:; frame-src blob:; connect-src blob: data:">` +
  `<style>${faces}html,body{margin:0;height:100%;overflow:hidden;-webkit-tap-highlight-color:transparent;-webkit-touch-callout:none}#book,foliate-view{display:block;width:100%;height:100%}</style>` +
  `</head><body><div id="book"></div><script>${code.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;

mkdirSync(join(here, 'dist'), { recursive: true });
writeFileSync(
  join(here, 'dist/reader-html.ts'),
  `// Generated by packages/reader/build.mjs. Do not edit.\n// foliate-js (MIT) © John Factotum. Fonts: SIL OFL.\n` +
    `export const READER_BUNDLE_VERSION = ${JSON.stringify(version)};\n` +
    `export const FONT_FACES: string = ${JSON.stringify(faces)};\n` +
    `export const readerHtml: string = ${JSON.stringify(html)};\n`,
);
console.log(`reader bundle ${version}: ${(html.length / 1024).toFixed(0)} KB`);
